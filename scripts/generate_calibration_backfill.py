"""
Generates the SQL that stores calibrated confidences on ai_match_logs.

    python scripts/generate_calibration_backfill.py [--out PATH]

The coefficients belong to the promoted artefact, not to a hand-typed SQL
literal, so they are read from it rather than copied. Mistyping one would
produce plausible-looking numbers that quietly disagreed with what the engine
serves, which is the kind of error nothing would catch.

Run this after `python -m eval.calibrate --promote` if the stored confidences
need to describe the new model, and give the output its OWN migration number.
Rewriting an applied migration would change history that has already run on
the live database; a recalibration is a deliberate act and deserves its own
traceable file.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

ARTIFACT = Path(__file__).parent.parent / "apps" / "ai-engine" / "artifacts" / "calibration.json"
DEFAULT_OUT = Path(__file__).parent.parent / "supabase" / "migrations" / "027_match_log_confidence.sql"

TEMPLATE = """-- Stores the calibrated match probability on each logged match, and
-- backfills the rows written before it existed.
--
-- GENERATED by scripts/generate_calibration_backfill.py from
-- apps/ai-engine/artifacts/calibration.json. Do not hand-edit the
-- coefficients; regenerate instead.
--
-- THE PROBLEM. ai_match_logs stored composite_score, the raw weighted sum,
-- and Match History rendered it as `composite_score * 100`. AI Matches shows
-- the calibrated figure instead. So the same gig read 61% when it was
-- recommended and 40% in the history of that recommendation, and a worker
-- comparing the two pages had no way to tell which number to believe.
--
-- The raw score stays. Every evaluation figure is computed from it and the
-- per-signal breakdown sums to it, so dropping it would make the history
-- unauditable. `confidence` is added alongside.
--
-- WHY BACKFILL RATHER THAN TRANSFORM ON READ. A stored number needs no engine
-- call to render a page, and the engine sleeps on its current plan. The
-- transform is a logistic, which Postgres applies exactly:
--
--   confidence = 1 / (1 + exp(-(a * composite_score + b)))
--
-- a = {a!r}
-- b = {b!r}
-- fitted on the {fitted_on} split of dataset {dataset_version}, over
-- {n_pairs} graded pairs ({n_relevant} relevant at grade >= {relevant_at}).

ALTER TABLE public.ai_match_logs
  ADD COLUMN IF NOT EXISTS confidence NUMERIC(5,4);

COMMENT ON COLUMN public.ai_match_logs.confidence IS
  'Calibrated P(relevant) for this recommendation: Platt scaling of '
  'composite_score, from apps/ai-engine/artifacts/calibration.json. Null only '
  'where composite_score was itself null and there was nothing to transform.';

-- The historical rows.
--
-- Clamped into the column's range on purpose. The logistic is open on (0, 1),
-- so it never truly reaches either end, but NUMERIC(5,4) cannot hold a value
-- that rounds past 1.0000 and an extreme composite would overflow it.
UPDATE public.ai_match_logs
   SET confidence = LEAST(
         0.9999,
         GREATEST(
           0.0001,
           1.0 / (1.0 + exp(-(
             {a!r}::DOUBLE PRECISION * composite_score::DOUBLE PRECISION
             + {b!r}::DOUBLE PRECISION
           )))
         )
       )
 WHERE confidence IS NULL
   AND composite_score IS NOT NULL;

-- After a recalibration the stored values describe the previous model. Fixing
-- that means a NEW migration with the new coefficients, not an edit to this
-- one: this file has already been applied, and changing it would make the
-- migration history disagree with the database it produced.
"""


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = parser.parse_args()

    if not ARTIFACT.exists():
        raise SystemExit(
            f"No calibration artefact at {ARTIFACT}. "
            "Run `python -m eval.calibrate --promote` first."
        )

    cal = json.loads(ARTIFACT.read_text(encoding="utf-8"))

    sql = TEMPLATE.format(
        a=cal["a"],
        b=cal["b"],
        fitted_on=cal.get("fitted_on", "?"),
        dataset_version=cal.get("dataset_version", "?"),
        n_pairs=cal.get("n_pairs", "?"),
        n_relevant=cal.get("n_relevant", "?"),
        relevant_at=cal.get("relevant_at", "?"),
    )
    args.out.write_text(sql, encoding="utf-8")

    print(f"wrote {args.out}")
    print(f"  a = {cal['a']}")
    print(f"  b = {cal['b']}")
    print(f"  fitted on {cal.get('fitted_on')} of dataset {cal.get('dataset_version')}")


if __name__ == "__main__":
    main()
